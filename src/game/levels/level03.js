import { median } from '../profile.js';

// 天花板可以壓到的兩個高度。第 10 列會擋掉滿力跳（升 51 px），
// 但仍留得下升 34 px 的中等跳——而中等跳足以跨過兩格刺，
// 所以不管側寫怎麼變，這一關永遠有解。
const CEIL_LOW = 10;
const CEIL_HIGH = 9;
const SLAB_X0 = 11;
const SLAB_X1 = 20;

// 超過這個高度就算「你習慣把跳躍鍵按到底」
const TALL_JUMP = 35;

function addSlab(tiles, row) {
  const out = tiles.slice();
  const cells = out[row].split('');
  for (let x = SLAB_X0; x <= SLAB_X1; x++) cells[x] = '#';
  out[row] = cells.join('');
  return out;
}

export default {
  id: 3,
  name: '你頭很硬',

  // 地板中間兩格是刺。天花板由 adapt() 依你的跳躍習慣放。
  tiles: [
    '##############################',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '##############^^##############',
    '##############################',
    '##############################',
  ],
  spawn: [3, 13],
  door: [24, 12],

  // 你還在助跑的時候，落點那兩格突然長出刺。沒有預告。
  // 安全落點因此只剩第 16、17 格——但那正好是被天花板壓矮的跳躍會到的地方。
  traps: [
    {
      when: { t: 'crossX', x: 10 },
      do: [{ t: 'spawnSpikes', x: 18, y: 14, w: 2, h: 1 }],
      once: true,
    },
  ],

  // 你習慣跳多高，天花板就壓到那個高度以下。
  // 滿力跳會撞到天花板，上升速度歸零，然後直直掉進刺裡。
  // 反制：改成點跳。矮的弧線反而過得去。
  adapt(tiles, profile) {
    const apex = median(profile.apexes);
    const row = apex !== null && apex >= TALL_JUMP ? CEIL_LOW : CEIL_HIGH;
    return { tiles: addSlab(tiles, row) };
  },
};
