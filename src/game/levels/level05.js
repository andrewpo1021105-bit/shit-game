import { median } from '../profile.js';

const FIELD_X0 = 6;      // 刺陣從這裡往右長
const RETRACT_AT = 3;    // 幾秒後刺會收起來
const WIDE = 6, MID = 4, NARROW = 2;

export default {
  id: 5,
  name: '你急什麼',

  tiles: [
    '##############################',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '##############################',
    '##############################',
    '##############################',
  ],
  spawn: [3, 13],
  door: [24, 12],

  // 這一關的刺可以寬到跳不過去，因為三秒後它會自己收起來。
  // 這面旗子是講給關卡驗證測試聽的：別把這排刺當成死路。
  spikesRetract: true,

  // 三秒後刺自己收起來（addTiles 直接把 '^' 蓋回 '#'）。
  // 這關唯一的解法是「什麼都不要做」。
  traps: [
    {
      when: { t: 'afterDelay', s: RETRACT_AT },
      do: [{ t: 'addTiles', x: FIELD_X0, y: 14, w: WIDE, h: 1 }],
      once: true,
    },
    // 你好不容易忍住等到刺收了，才剛走出去就有方塊砸下來
    {
      when: { t: 'crossX', x: 13 },
      do: [{ t: 'dropBlock', x: 17, y: 2 }],
      once: true,
    },
  ],

  // 你死了之後多快開始動，決定刺陣有多寬。
  // 越急的人擋得越遠，逼你非等不可。
  adapt(tiles, profile) {
    const delay = median(profile.restartDelays);
    const width = delay === null ? MID : delay < 0.5 ? WIDE : delay < 1.5 ? MID : NARROW;

    const out = tiles.slice();
    const cells = out[14].split('');
    for (let x = FIELD_X0; x < FIELD_X0 + width; x++) cells[x] = '^';
    out[14] = cells.join('');

    // 不解釋。刺會不會收、什麼時候收，玩家得自己死出來。
    return { tiles: out };
  },
};
