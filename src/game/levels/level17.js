export default {
  id: 17,
  name: '結算之前',

  // 最後一關,三種敵人同台:巡邏的、突進的、守株待兔的。
  // 走完這裡就是排行榜——而它連「你已經走完了」都要再騙你一次。
  tiles: [
    '##############################',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '##############################',
    '##############################',
    '##############################',
  ],
  spawn: [3, 13],
  door: [24, 12],

  announce: '最後了，這次是真的',

  decoys: [[19, 7]],

  enemies: [
    { kind: 'charger', x: 13, y: 13, min: 9, max: 16, speed: 32, sight: 7 },
    { kind: 'spitter', x: 22, y: 13, dir: -1, range: 12 },
  ],

  traps: [
    // 一、穿過殭屍的地盤之後,一隻巡邏獸從門口出發朝你走來——
    //     排行榜的計時還在跑,而路變窄了。
    {
      when: { t: 'crossX', x: 14 },
      do: [{ t: 'spawnEnemy', kind: 'walker', x: 20, y: 13, min: 16, max: 22, speed: 44 }],
      once: true,
    },
    // 二、死了兩次,半空中多一扇假門陪著原本那扇
    {
      when: { t: 'deathCount', n: 2 },
      do: [{ t: 'spawnDecoy', x: 15, y: 7 }],
      once: true,
    },
    // 三、門前最後兩格,頭頂砸下方塊。你在躲怪、在看計時、在想排名——
    //     就是沒在看天上。
    {
      when: { t: 'standOn', x: 23, y: 14 },
      do: [{ t: 'dropBlock', x: 26, y: 5 }],
      once: true,
    },
    // 門前那一下由 adapt() 決定,因為它要看你在這一關死過幾次
  ],

  // 只有一條命都沒丟的人才會被最後這個謊騙到。
  // fakeWin 演完會把真門跟半空的假門交換,而那扇假門吊在搆不到的高度——
  // 你必須死一次,門才會變回真的。死過之後改演假死:
  // 嚇你,但不偷你的時間。重複同一個謊只是刁難,不是欺騙。
  adapt(tiles, profile, ctx = {}) {
    const deaths = ctx.deaths ?? 0;
    return {
      tiles: tiles.slice(),
      traps: [
        ...this.traps,
        deaths === 0
          ? {
            // 四、你碰到門——CLEAR! 跳出來了,音樂響了,你在心裡算名次。
            //     然後畫面收回去,你站的地方是一扇假門。
            //     整場遊戲的最後一句話還是謊話。計時器可沒停。
            when: { t: 'touchDoor' },
            do: [{ t: 'fakeWin', s: 1.2 }],
            once: true,
          }
          : {
            // 死過的人碰到門,改演一次假死。你已經不會信它了——
            //     但你的手會信。
            when: { t: 'touchDoor' },
            do: [{ t: 'fakeDeath', s: 0.5 }],
            once: true,
          },
      ],
    };
  },
};
