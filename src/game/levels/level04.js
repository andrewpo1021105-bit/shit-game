import { median } from '../profile.js';

const DOOR_X = 18;      // 門一開始就在明顯的地方
const ZONE_X0 = 12;     // 進入這一段門就開始逃
const ZONE_X1 = 26;
const FAST = 0.11;      // 逃跑間隔（秒/格）——越小逃得越快
const SLOW = 0.17;
const BRISK_WALKER = 90;

export default {
  id: 4,
  name: '你的步伐我量過了',

  // 一條完全空的平路。沒有洞、沒有刺、沒有天花板。
  tiles: [
    '##############################',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '#............................#',
    '##############################',
    '##############################',
    '##############################',
  ],
  spawn: [3, 13],
  door: [DOOR_X, 12],
  traps: [],

  // 你一走進門的地盤，門就開始往右退，而且退得比你走得快。
  // 逃到右牆就無處可逃了，所以這關一定過得了——
  // 但在你把它逼到牆角之前，你會一直以為自己快碰到了。
  adapt(tiles, profile) {
    const speed = median(profile.speeds);
    const interval = speed !== null && speed >= BRISK_WALKER ? FAST : SLOW;

    return {
      tiles: tiles.slice(),
      traps: [
        // 一、你一走近，門就開始往右退，退到牆角才停
        {
          when: { t: 'enterRect', x: ZONE_X0, y: 1, w: ZONE_X1 - ZONE_X0, h: 15 },
          do: [{ t: 'moveDoor', x: 1, y: 0 }],
          every: interval,
        },
        // 二、你把它逼到牆角、正要走過去收尾——腳下的地板消失
        {
          when: { t: 'standOn', x: 25, y: 14 },
          do: [{ t: 'removeTiles', x: 25, y: 14, w: 1, h: 3 }],
          once: true,
        },
        // 三、真的碰到門了，門在判定過關前一瞬間往上跳走
        {
          when: { t: 'touchDoor' },
          do: [{ t: 'moveDoor', x: 0, y: -2 }],
          once: true,
        },
      ],
    };
  },
};
